"""Scanner output alongside one real page.

The judgement is the level: git status lists four files and the
student decides which belong in the records.
"""

ANCHOR = "tutorial/act1-desk"

PAGE = """\
# Opening checks

Before the first delivery of the day:

    roller doors     open, and the stops are down
    pallet jacks     wheels clear, handle returns
    scanners         charged, and logged in as yourself
"""

GENERATED = "# generated by the scanner export, do not edit\nbin,count\n"


def setup(repo, state):
    repo.require_refs(ANCHOR)
    repo.switch("main", create_if_missing_at=ANCHOR)
    repo.reset_hard(ANCHOR)
    repo.clean(untracked=True, ignored=True)

    repo.write_file("docs/opening-checks.md", PAGE)
    for aisle in ("a", "b", "c"):
        repo.write_file(f"scanner-export/aisle-{aisle}.csv", GENERATED)
